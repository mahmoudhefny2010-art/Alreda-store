BEGIN;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM payment_proofs) OR EXISTS (SELECT 1 FROM orders WHERE payment_method='INSTAPAY') THEN
    RAISE EXCEPTION 'REFUSE_ROLLBACK_WITH_INSTAPAY_DATA';
  END IF;
END $$;
DROP TABLE payment_proofs;
ALTER TABLE orders DROP CONSTRAINT orders_payment_check;
ALTER TABLE orders ADD CONSTRAINT orders_payment_check CHECK (payment_method IN ('CASH_ON_DELIVERY','INSTAPAY_ON_DELIVERY','PAY_AT_CASHIER','ONLINE'));
COMMIT;
